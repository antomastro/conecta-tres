const CLAVE = "c3idioma";

const esIdioma = (x: string): x is Idioma => IDIOMAS.some((i) => i.id === x);

// Idioma guardado o, si no hay, el del móvil; si no lo tenemos, español.
export function idiomaInicial(): Idioma {
  try {
    const guardado = localStorage.getItem(CLAVE);
    if (guardado && esIdioma(guardado)) return guardado;
  } catch {
    /* sin almacenamiento disponible */
  }
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = l.slice(0, 2).toLowerCase();
    if (esIdioma(base)) return base;
  }
  return "es";
}

export function guardarIdioma(id: Idioma) {
  try {
    localStorage.setItem(CLAVE, id);
  } catch {
    /* sin almacenamiento disponible */
  }
}

export const TextosContext = createContext<Textos>(es);

export const useTextos = () => useContext(TextosContext);
